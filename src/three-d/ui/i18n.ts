export type Lang = 'en' | 'ro';

export function resolveLang(setting: 'auto' | Lang, hass: unknown): Lang {
	if (setting === 'en' || setting === 'ro') return setting;
	const h = hass as {
		locale?: { language?: string };
		language?: string;
		selectedLanguage?: string;
	} | null;
	let stored = '';
	try {
		stored = (localStorage.getItem('selectedLanguage') ?? '').replace(/"/g, '');
	} catch {
		/* storage may be blocked */
	}
	const lang = String(
		h?.selectedLanguage || h?.locale?.language || h?.language || stored || 'en',
	).toLowerCase();
	return lang.startsWith('ro') ? 'ro' : 'en';
}

export function translator(lang: Lang) {
	const dict = lang === 'ro' ? ro : en;
	return (key: I18nKey, vars?: Record<string, string | number>): string => {
		let s = dict[key] ?? en[key] ?? key;
		if (vars)
			for (const [k, v] of Object.entries(vars))
				s = s.replace(`{${k}}`, String(v));
		return s;
	};
}

export type Translate = ReturnType<typeof translator>;
